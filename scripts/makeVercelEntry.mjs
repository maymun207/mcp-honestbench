/**
 * makeVercelEntry.mjs — emit the Vercel output directory.
 *
 * WHY A SHIM DIRECTORY INSTEAD OF POINTING VERCEL AT `dist/`:
 * Vercel's Node/Express preset picks a server entrypoint BY FILENAME from the
 * output directory, searching `app.*`, `index.*`, `server.*`, `src/*`. Our own
 * `src/server.ts` compiles to `dist/server.js` — the MCP wiring module, which
 * exports `createApp`/`createFlatServer` and no app — and the preset selected
 * THAT, failing with:
 *
 *   Invalid export found in module "/var/task/dist/server.js".
 *   The default export must be a function or server.
 *
 * Renaming our module would have edited `src/index.ts`, which the GO requires to
 * stay byte-unchanged. So instead the output directory contains exactly ONE
 * candidate file, and there is nothing left to guess: `vercel-build/index.js`
 * re-exports the app from `dist/app.js`. `src/index.ts`, `src/server.ts` and the
 * Dockerfile are all untouched.
 */
import { mkdirSync, writeFileSync } from 'node:fs';

const DIR = 'vercel-build';
const ENTRY = `${DIR}/index.js`;

mkdirSync(DIR, { recursive: true });
writeFileSync(
    ENTRY,
    `// GENERATED by scripts/makeVercelEntry.mjs — do not edit.\n` +
        `// The single entrypoint candidate in this directory, so Vercel's preset\n` +
        `// cannot select one of the instrument's own modules by name.\n` +
        `export { default } from '../dist/app.js';\n`,
    'utf8',
);

console.log(`[honestbench] wrote ${ENTRY} -> ../dist/app.js`);
